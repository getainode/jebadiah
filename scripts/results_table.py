"""Build results/SUMMARY.md from the per-run records under results/.

  python scripts/results_table.py            # writes results/SUMMARY.md and prints it

Every number comes from results/runs/<run>/results.json (the headline block and the eval block),
results/nonce/<run>/*.json and results/jevbench/<label>/public-metrics.json.
"""
from __future__ import annotations

import glob
import json
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "results")
HEAD = ["jevals-pubmedqa", "jevals-banking77", "jevals-helpsteer2", "nimble-eval", "kev-transfer-v4__test"]
# the six human-labelled yes/no (noul) eval sets, pooled by item count
HUMAN_NOUL = ["jevals-pubmedqa", "nimble-public__boolq", "nimble-public__paws", "nimble-public__squad2",
              "nimble-public__aegis2", "nimble-public__civil_comments"]
PUBLISHED = {"4b-v0": "4B v0", "9b-v0": "9B v0", "4b-v1": "4B v1", "9b-v1": "9B v1",
             "4b-chat-v1": "4B v2", "9b-chat-v1": "9B v2"}


def load_runs() -> dict[str, dict]:
    runs = {}
    for p in sorted(glob.glob(os.path.join(ROOT, "runs", "*", "results.json"))):
        d = json.load(open(p))
        if d.get("stage") == "complete" and d.get("headline"):
            runs[d["run"]] = d
    return runs


def f1(x) -> str:
    return "" if x is None else f"{x:.1f}"


def pooled_noul(ev: dict) -> float | None:
    if not all(s in ev for s in HUMAN_NOUL):
        return None
    n = sum(ev[s]["n"] for s in HUMAN_NOUL)
    return 100 * sum(ev[s]["accuracy"] * ev[s]["n"] for s in HUMAN_NOUL) / n


def row(name: str, d: dict) -> list[str]:
    h, ev = d["headline"], d["eval"]
    c = h["components"]
    base = d["config"]["base_model"].split("/")[-1]
    data = os.path.basename(d["config"]["data_dir"]) if d["config"].get("data_dir") else "data"
    mins = (d.get("minutes") or {}).get("train")
    return [f"`{name}`", PUBLISHED.get(name, ""), base, data, f"{h['headline']:.2f}"] + \
        [f1(c.get(s)) for s in HEAD] + [f1(c.get("nimble-public (macro over 13)")), f1(pooled_noul(ev)),
                                        f1(ev["jevals-helpsteer2"].get("decision_score_jevals")),
                                        f"{ev['nimble-eval']['ece']:.3f}", f1(mins)]


def table(runs: dict[str, dict], names: list[str]) -> list[str]:
    hdr = ["run", "published as", "base", "pool", "headline", "Jevals PubMedQA", "Jevals Banking77", "Jevals HelpSteer2",
           "Nimble 324", "Kev transfer", "Nimble 13 macro", "human yes/no pooled 6", "DSj HelpSteer2",
           "Nimble 324 ECE", "train min"]
    out = ["| " + " | ".join(hdr) + " |", "|" + "---|" * len(hdr)]
    out += ["| " + " | ".join(row(n, runs[n])) + " |" for n in names if n in runs]
    return out


def nonce_rows() -> list[str]:
    out = ["| run | set | pick agreement (state nonce) | any flip | accuracy clean | accuracy with nonce |", "|---|---|---|---|---|---|"]
    for d in sorted(glob.glob(os.path.join(ROOT, "nonce", "*"))):
        for p in sorted(glob.glob(os.path.join(d, "*.json"))):
            o = json.load(open(p))["overall"]["state"]
            out.append(f"| `{os.path.basename(d)}` | {os.path.basename(p)[:-5]} | {o['pick_agreement']:.3f} | "
                       f"{o['any_flip_rate']:.3f} | {o['accuracy_clean']:.3f} | {o['accuracy_nonce']:.3f} |")
    return out


def jevbench_rows() -> list[str]:
    out = ["| label | public acc (231) | easy | standard | hard (111) | ECE all | ECE hard | Brier hard | calibration formula, public hard |",
           "|---|---|---|---|---|---|---|---|---|"]
    for p in sorted(glob.glob(os.path.join(ROOT, "jevbench", "*", "public-metrics.json"))):
        m = json.load(open(p)); t = m["tiers_public"]
        out.append(f"| `{os.path.basename(os.path.dirname(p))}` | {m['public_accuracy']:.3f} | {t['easy']['correct']}/48 | "
                   f"{t['original']['correct']}/72 | {t['hard']['correct']}/111 | {m['ece_all']:.3f} | {m['ece_hard']:.3f} | "
                   f"{m['brier_mean_hard']:.3f} | {m['calibration_v13_formula_public_hard_only']:.1f} |")
    return out


def main() -> None:
    runs = load_runs()
    pub = [n for n in PUBLISHED if n in runs]
    rest = sorted(n for n in runs if n not in PUBLISHED)
    L = ["# Results summary", "",
         "Generated by `scripts/results_table.py` from the records in this directory. Accuracy in percent, repeat 0.",
         "Headline = macro over Jevals PubMedQA, Banking77, HelpSteer2, Nimble 324, Kev transfer and the Nimble 13 public",
         "subsets counted as one. Human yes/no pooled 6 = accuracy over the 1,699 items of Jevals PubMedQA and the Nimble",
         "public BoolQ, PAWS, SQuAD2, Aegis2 and Civil Comments sets. DSj = Jevals Decision Score (0 = base-rate guessing).",
         "", "## Published models", ""] + table(runs, pub) + \
        ["", "## Every other run", ""] + table(runs, rest) + \
        ["", "## Nonce robustness (a random id planted in the state, 3 passes per question)", ""] + nonce_rows() + \
        ["", "## JevBench v1.4.2, 231 public items", ""] + jevbench_rows() + [""]
    text = "\n".join(L)
    open(os.path.join(ROOT, "SUMMARY.md"), "w").write(text)
    print(text)


if __name__ == "__main__":
    main()
